#!/usr/bin/env bash
# Idempotent, safe-to-rerun bootstrap for the NetBox stack (Phase 1).
#
#   1. Generate netbox/.env with fresh random secrets, but only if it does
#      not already exist -- never overwrites/rotates existing secrets.
#   2. Start (or converge) the NetBox Compose stack.
#   3. Wait for NetBox to report healthy.
#   4. Ensure the IaC client's API token exists (delegates to
#      ensure_api_token.py, itself idempotent).
#
# Never touches Containerlab or the monitoring/ (InfluxDB/Grafana) stack.
set -euo pipefail

NETBOX_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$NETBOX_DIR"

ENV_FILE="$NETBOX_DIR/.env"

if [[ -e "$ENV_FILE" ]]; then
    echo "netbox/.env already exists; leaving existing secrets untouched."
else
    echo "Generating netbox/.env with freshly-random secrets..."
    umask 077
    postgres_password=$(openssl rand -hex 24)
    redis_password=$(openssl rand -hex 24)
    redis_cache_password=$(openssl rand -hex 24)
    secret_key=$(openssl rand -base64 48 | tr -d '\n=+/' )
    # Django's SECRET_KEY tolerates base64 punctuation, but stripping it above
    # can shorten the string below NetBox's recommended 50 chars; top it up.
    while [[ ${#secret_key} -lt 50 ]]; do
        secret_key+="$(openssl rand -hex 8)"
    done
    api_token_pepper=$(openssl rand -hex 32)
    superuser_password=$(openssl rand -hex 16)

    cat > "$ENV_FILE" <<EOF
# Generated by netbox/scripts/bootstrap_netbox.sh on $(date -Is)
# Real runtime secrets -- NEVER commit this file (see .gitignore).
POSTGRES_DB=netbox
POSTGRES_USER=netbox
POSTGRES_PASSWORD=$postgres_password
DB_NAME=netbox
DB_USER=netbox
DB_PASSWORD=$postgres_password
DB_HOST=postgres
REDIS_HOST=redis
REDIS_PASSWORD=$redis_password
REDIS_CACHE_HOST=redis-cache
REDIS_CACHE_PASSWORD=$redis_cache_password
SECRET_KEY=$secret_key
API_TOKEN_PEPPER_1=$api_token_pepper
SKIP_SUPERUSER=false
SUPERUSER_NAME=nmas-admin
SUPERUSER_EMAIL=nmas-admin@example.invalid
SUPERUSER_PASSWORD=$superuser_password
NETBOX_URL=http://127.0.0.1:8000
NETBOX_TOKEN=
NETBOX_TIMEOUT=10
NETBOX_VERIFY_SSL=true
EOF
    chmod 600 "$ENV_FILE"
    echo "netbox/.env created (mode 600)."
fi

if [[ ! -f "$ENV_FILE" ]] || [[ $(stat -c '%a' "$ENV_FILE") != "600" ]]; then
    echo "Refusing to continue: netbox/.env must be a regular, mode-600 file." >&2
    exit 1
fi

echo "Starting the NetBox stack (postgres, redis, redis-cache, netbox, netbox-worker)..."
docker compose --env-file "$ENV_FILE" -f "$NETBOX_DIR/docker-compose.yml" up -d --wait --wait-timeout 180

echo "Ensuring the IaC API token exists..."
python3 "$NETBOX_DIR/scripts/ensure_api_token.py"

echo "NetBox bootstrap complete."
