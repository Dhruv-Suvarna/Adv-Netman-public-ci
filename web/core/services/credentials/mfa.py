"""Human device-login MFA policy and non-live candidate rendering.

The authoritative Phase-24 human mechanism is a named password plus a
standards-based TOTP generated by Microsoft Authenticator.  EOS sends one
``User-Password`` value (``password`` immediately followed by the six-digit
TOTP) to a local RADIUS service.  The service independently validates both
factors.  This single-shot path deliberately does not depend on RADIUS
Access-Challenge support in the EOS SSH client.

The EOS method list is ``local`` then the named human-MFA RADIUS group.  A
dedicated local NMAS service identity therefore remains non-interactive, while
human usernames MUST be absent from the EOS local user database and fall
through to RADIUS.  Legacy SSH-key + password helpers remain below because the
key-loading path is still useful for machine identities and existing Phase-23
dependencies; they are no longer the human 2FA architecture.

Rendering is offline.  Only the explicitly legacy ``probe_two_factor_login``
helper contacts an SSH endpoint, and it never changes configuration.
"""
from __future__ import annotations

import base64
import hashlib
import re
from dataclasses import dataclass, field

from ...models import AccountKind, DeviceAuthMethod, MfaMechanism

LEGACY_CEOS_MFA_PROTOCOL = "authentication protocol multi-factor public-key password"
RADIUS_GROUP = "NMAS-HUMAN-MFA"
RADIUS_SHARED_SECRET_PLACEHOLDER = "<provider:{reference}>"
OPENSSH_DROPIN_PATH = "/etc/ssh/sshd_config.d/60-nmas-two-factor.conf"
LINUX_MFA_OPENSSH_DROPIN_PATH = "/etc/ssh/sshd_config.d/60-nmas-human-mfa.conf"
_PUBLIC_KEY_RE = re.compile(r"^(ssh-ed25519|ecdsa-sha2-nistp256|ecdsa-sha2-nistp384|ssh-rsa) ([A-Za-z0-9+/]+={0,2})(?: ([\w.@-]{1,64}))?$")
_NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_.-]{0,63}$")


class MfaConfigError(ValueError):
    """Invalid enrollment metadata; messages never contain key or password material."""


def parse_public_key(line: str) -> tuple[str, str, str]:
    """Validate one OpenSSH PUBLIC key line -> (type, base64 blob, comment)."""
    text = (line or "").strip()
    if "PRIVATE KEY" in text:
        raise MfaConfigError("A private key was supplied where a public key is required.")
    match = _PUBLIC_KEY_RE.fullmatch(text)
    if not match:
        raise MfaConfigError("Not a supported single-line OpenSSH public key.")
    key_type, blob, comment = match.group(1), match.group(2), match.group(3) or ""
    try:
        raw = base64.b64decode(blob, validate=True)
    except ValueError:
        raise MfaConfigError("Public key body is not valid base64.") from None
    # The wire blob starts with the length-prefixed key type; reject mismatches.
    if len(raw) < 4 or raw[4:4 + int.from_bytes(raw[:4], "big")].decode(errors="replace") != key_type:
        raise MfaConfigError("Public key body does not match its declared type.")
    return key_type, blob, comment


def public_key_fingerprint(line: str) -> str:
    """OpenSSH-compatible ``SHA256:<base64>`` fingerprint (non-secret)."""
    _type, blob, _comment = parse_public_key(line)
    digest = hashlib.sha256(base64.b64decode(blob)).digest()
    return "SHA256:" + base64.b64encode(digest).decode().rstrip("=")


def generate_service_keypair(comment: str) -> tuple[str, str, str]:
    """New Ed25519 keypair -> (private OpenSSH PEM, public line, fingerprint).

    Uses ``cryptography`` (the library paramiko itself depends on); no
    home-grown crypto.  The private half must go straight to the provider.
    """
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    if not re.fullmatch(r"[\w.@-]{1,64}", comment):
        raise MfaConfigError("Key comment must be a short token.")
    key = Ed25519PrivateKey.generate()
    private = key.private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.OpenSSH, serialization.NoEncryption(),
    ).decode()
    public = key.public_key().public_bytes(serialization.Encoding.OpenSSH, serialization.PublicFormat.OpenSSH).decode()
    public = f"{public} {comment}"
    return private, public, public_key_fingerprint(public)


