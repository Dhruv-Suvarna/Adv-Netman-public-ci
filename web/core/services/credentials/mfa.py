@dataclass(frozen=True)
class MfaAccount:
    username: str
    kind: str
    public_key: str
    role: str = ""
    privilege: int | None = None
    secret_ref: str = ""
    create_account: bool = False


@dataclass
class MfaCandidate:
    device: str
    platform: str
    supported: bool
    lines: list[str] = field(default_factory=list)
    prepare_lines: list[str] = field(default_factory=list)
    activation_lines: list[str] = field(default_factory=list)
    rollback_lines: list[str] = field(default_factory=list)
    blockers: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    @property
    def digest(self) -> str:
        body = "\n".join([self.device, self.platform, *self.lines, "--rollback--", *self.rollback_lines])
        return hashlib.sha256(body.encode()).hexdigest()

    def as_dict(self) -> dict:
        return {
            "device": self.device, "platform": self.platform, "supported": self.supported,
            "lines": list(self.lines), "rollback_lines": list(self.rollback_lines),
            "prepare_lines": list(self.prepare_lines), "activation_lines": list(self.activation_lines),
            "blockers": list(self.blockers), "notes": list(self.notes), "digest": self.digest,
        }


def legacy_accounts_from_credentials(credentials) -> list[MfaAccount]:
    """Project legacy SSH-key + password rows; not human TOTP enrollment."""
    accounts = []
    for row in credentials:
        if row.auth_method != DeviceAuthMethod.PUBLICKEY_AND_PASSWORD or not row.ssh_public_key:
            continue
        accounts.append(MfaAccount(
            username=row.username, kind=row.account_kind, public_key=row.ssh_public_key.strip(),
            role=row.account_role, privilege=row.privilege_level, secret_ref=row.secret_ref,
            create_account=row.account_kind == AccountKind.SERVICE,
        ))
    return accounts


def _ordered(accounts):
    order = {AccountKind.SERVICE: 0, AccountKind.BREAK_GLASS: 1, AccountKind.HUMAN: 2}
    return sorted(accounts, key=lambda a: (order.get(a.kind, 9), a.username))


def _require_lockout_safety(accounts) -> list[str]:
    blockers = []
    if not any(a.kind == AccountKind.SERVICE for a in accounts):
        blockers.append("NO_ENROLLED_SERVICE_ACCOUNT: enforcing would lock NMAS automation out")
    if not any(a.kind in (AccountKind.HUMAN, AccountKind.BREAK_GLASS) for a in accounts):
        blockers.append("NO_ENROLLED_HUMAN_OR_BREAK_GLASS_ACCOUNT: no interactive administrator could log in over SSH")
    return blockers


def render_legacy_ceos_candidate(device: str, accounts: list[MfaAccount], *, disable_eapi: bool = True) -> MfaCandidate:
    candidate = MfaCandidate(device=device, platform="arista_ceos", supported=True)
    for account in accounts:
        if not _NAME_RE.fullmatch(account.username):
            raise MfaConfigError("Invalid account name.")
        parse_public_key(account.public_key)
    accounts = _ordered(accounts)
    candidate.blockers = _require_lockout_safety(accounts)

    # Console keeps its own local method list: the container console is the
    # documented emergency path and never goes through management ssh.
    lines = ["aaa authentication login console local"]
    for account in accounts:
        if account.create_account:
            head = ["username", account.username]
            if account.privilege is not None:
                head += ["privilege", str(account.privilege)]
            if account.role:
                head += ["role", account.role]
            # The provider value is substituted only at execution time.
            lines.append(" ".join(head + ["secret", f"<provider:{account.secret_ref}>"]))
        lines.append(f"username {account.username} ssh-key {account.public_key}")
    lines += ["management ssh", f"   {LEGACY_CEOS_MFA_PROTOCOL}"]
    if disable_eapi:
        # eAPI (HTTPS) authenticates with a password alone; it is enabled by
        # the cEOS default startup config, unused by NMAS, and would be a
        # single-factor bypass of the SSH policy.
        lines += ["management api http-commands", "   shutdown"]
    candidate.lines = lines

    rollback = ["management ssh", "   default authentication protocol"]
    if disable_eapi:
        rollback += ["management api http-commands", "   no shutdown"]
    rollback += [f"no username {a.username} ssh-key" for a in accounts if not a.create_account]
    rollback += [f"no username {a.username}" for a in accounts if a.create_account]
    rollback.append("no aaa authentication login console")
    candidate.rollback_lines = rollback
    candidate.notes = [
        "gNMI (port 6030) authenticates the read-only nmas-telemetry service account with a password; it is a machine "
        "telemetry plane, not an interactive login, and stays single-factor (documented residual risk).",
        "NETCONF-over-SSH behaviour under the multi-factor policy must be verified in the live test plan before activation.",
    ]
    return candidate


def render_legacy_openssh_candidate(device: str, accounts: list[MfaAccount], *, root_only: bool) -> MfaCandidate:
    candidate = MfaCandidate(device=device, platform="ubuntu_frr", supported=True)
    for account in accounts:
        parse_public_key(account.public_key)
    candidate.lines = [
        f"# {OPENSSH_DROPIN_PATH} -- rendered by NMAS; two factors for every SSH login",
        "PubkeyAuthentication yes",
        "PasswordAuthentication yes",
        "KbdInteractiveAuthentication no",
        "AuthenticationMethods publickey,password",
    ]
    candidate.rollback_lines = [f"rm -f {OPENSSH_DROPIN_PATH}", "sshd -t && kill -HUP $(cat /run/sshd.pid)"]
    candidate.blockers = _require_lockout_safety(_ordered(accounts))
    if root_only:
        candidate.blockers.insert(0, "ROOT_ONLY_ACCOUNT: a dedicated non-root automation account is required first")
    candidate.notes = ["R3/R4 have no systemd; sshd is reloaded by signal, and docker exec remains the emergency path."]
    return candidate


def _radius_policy_blockers(device: str, credentials) -> list[str]:
    rows = list(credentials)
    blockers = []
    service_rows = [
        row for row in rows
        if row.account_kind == AccountKind.SERVICE and row.username == "nmas-automation"
    ]
    break_glass_rows = [row for row in rows if row.account_kind == AccountKind.BREAK_GLASS]
    human_rows = [row for row in rows if row.account_kind == AccountKind.HUMAN]
    legacy_admin_rows = [
        row for row in rows
        if row.account_kind == AccountKind.LEGACY_SHARED and row.username == "admin"
    ]
    if len(service_rows) != 1:
        blockers.append("NO_LOCAL_NMAS_SERVICE_IDENTITY: create and verify the dedicated automation account before rollout")
    expected_break_glass = f"{device.lower()}-breakglass"
    if len(break_glass_rows) != 1 or break_glass_rows[0].username != expected_break_glass:
        blockers.append("NO_SEALED_BREAK_GLASS_IDENTITY: create and verify a unique emergency account before activation")
    if len(human_rows) != 1 or human_rows[0].auth_method != DeviceAuthMethod.PASSWORD_AND_TOTP:
        blockers.append("NO_CENTRAL_TOTP_HUMAN: enroll a named human in privacyIDEA before rollout")
    if len(legacy_admin_rows) != 1:
        blockers.append("NO_EXACT_LEGACY_ADMIN_ROLLBACK: retain one protected admin metadata row until rollback is proven")
    return blockers


def _linux_radius_policy_blockers(device: str, credentials) -> list[str]:
    rows = list(credentials)
    service = [row for row in rows if row.account_kind == AccountKind.SERVICE and row.username == "nmas-automation"]
    human = [row for row in rows if row.account_kind == AccountKind.HUMAN and row.username == "nmas-admin"]
    break_glass = [row for row in rows if row.account_kind == AccountKind.BREAK_GLASS]
    legacy_root = [row for row in rows if row.account_kind == AccountKind.LEGACY_SHARED and row.username == "root"]
    blockers = []
    if (len(service) != 1 or service[0].auth_method != DeviceAuthMethod.PUBLICKEY
            or not service[0].ssh_key_ref or not service[0].ssh_public_key
            or not service[0].ssh_public_key_fingerprint):
        blockers.append("NO_LINUX_PUBLICKEY_SERVICE_IDENTITY: enroll one nmas-automation public-key-only identity")
    if len(human) != 1 or human[0].auth_method != DeviceAuthMethod.PASSWORD_AND_TOTP:
        blockers.append("NO_CENTRAL_TOTP_HUMAN: enroll nmas-admin metadata without storing its factors")
    expected = f"{device.lower()}-breakglass"
    if len(break_glass) != 1 or break_glass[0].username != expected or not break_glass[0].secret_ref:
        blockers.append("NO_SEALED_BREAK_GLASS_IDENTITY: create one device-specific protected emergency identity")
    if len(legacy_root) != 1:
        blockers.append("NO_ROOT_RECOVERY_METADATA: retain the existing local-root metadata for console recovery")
    return blockers


def render_linux_radius_totp_candidate(policy, credentials) -> MfaCandidate:
    """Render secret-free Ubuntu/OpenSSH/PAM intent for reviewed R3/R4 rollout."""
    if policy.device_name not in ("R3", "R4"):
        raise MfaConfigError("Linux RADIUS/TOTP rollout is restricted to R3 and R4.")
    if not policy.radius_secret_ref.startswith("runtime://human-mfa/radius/"):
        raise MfaConfigError("RADIUS shared secret must use a protected runtime reference.")
    candidate = MfaCandidate(device=policy.device_name, platform="ubuntu_frr", supported=True)
    candidate.prepare_lines = [
        "package libpam-radius-auth", "account nmas-admin (central factors only)",
        "account nmas-automation (SSH public key only)", f"account {policy.device_name.lower()}-breakglass (local emergency password)",
    ]
    candidate.activation_lines = [
        "/etc/pam_radius_auth.conf mode 0600 (protected value substituted on stdin)",
        "/etc/pam.d/sshd routes only nmas-admin to pam_radius_auth.so",
        f"{LINUX_MFA_OPENSSH_DROPIN_PATH} requires keyboard-interactive:pam for nmas-admin",
        "nmas-automation requires publickey and is source-restricted to NMAS",
        f"{policy.device_name.lower()}-breakglass requires local password and is source-restricted to NMAS",
        "root and ubuntu SSH are denied; docker exec remains privileged recovery",
    ]
    candidate.lines = [*candidate.prepare_lines, *candidate.activation_lines]
    candidate.rollback_lines = [
        "restore exact PAM/sshd files from the device-local protected backup",
        "remove only Phase-26B-created accounts and reload the prior sshd configuration",
    ]
    candidate.blockers = _linux_radius_policy_blockers(policy.device_name, credentials)
    candidate.notes = [
        "A host-side transient systemd timer is armed before account or PAM/sshd mutation.",
        "RADIUS unavailability is fail-closed for nmas-admin; local break-glass and docker exec remain independent.",
        "Human input is one non-echoed password immediately followed by the current six-digit TOTP.",
    ]
    return candidate


def _local_account_line(row) -> str:
    if not _NAME_RE.fullmatch(row.username):
        raise MfaConfigError("Invalid local account name.")
    if not isinstance(row.secret_ref, str) or not row.secret_ref.startswith("runtime://device-credentials/"):
        raise MfaConfigError("Local accounts require protected runtime://device-credentials/<key> references.")
    parts = ["username", row.username]
    if row.privilege_level is not None:
        parts.extend(("privilege", str(row.privilege_level)))
    if row.account_role:
        if not _NAME_RE.fullmatch(row.account_role):
            raise MfaConfigError("Invalid local account role.")
        parts.extend(("role", row.account_role))
    parts.extend(("secret", RADIUS_SHARED_SECRET_PLACEHOLDER.format(reference=row.secret_ref)))
    return " ".join(parts)


def render_ceos_radius_totp_candidate(policy, credentials) -> MfaCandidate:
    """Render the exact non-live EOS 4.36.2F human-TOTP candidate.

    The shared secret is a provider reference placeholder.  It must be
    substituted from protected runtime storage only during an explicitly
    authorized rollout; this renderer never resolves it.
    """
    if not policy.radius_secret_ref.startswith("runtime://human-mfa/radius/"):
        raise MfaConfigError("RADIUS shared secret must use a protected runtime://human-mfa/radius/<device> reference.")
    if not policy.radius_source_interface:
        raise MfaConfigError("RADIUS source interface is required for an EOS candidate.")
    secret = RADIUS_SHARED_SECRET_PLACEHOLDER.format(reference=policy.radius_secret_ref)
    server = str(policy.radius_server)
    candidate = MfaCandidate(device=policy.device_name, platform="arista_ceos", supported=True)
    account_order = {
        AccountKind.SERVICE: 0,
        AccountKind.BREAK_GLASS: 1,
        AccountKind.HUMAN: 2,
        AccountKind.LEGACY_SHARED: 3,
    }
    rows = sorted(credentials, key=lambda row: (account_order.get(row.account_kind, 9), row.username))
    local_rows = [
        row for row in rows
        if row.account_kind == AccountKind.BREAK_GLASS
        or (row.account_kind == AccountKind.SERVICE and row.username == "nmas-automation")
    ]
    legacy_rows = [row for row in rows if row.account_kind == AccountKind.LEGACY_SHARED]
    prepare = [_local_account_line(row) for row in local_rows]
    activation = [f"no username {row.username}" for row in legacy_rows] + [
        f"radius-server host {server} key 0 {secret}",
        f"aaa group server radius {RADIUS_GROUP}",
        f"   server {server}",
        f"ip radius source-interface {policy.radius_source_interface}",
        "aaa authentication login console local",
        f"aaa authentication login default local group {RADIUS_GROUP}",
        # EOS applies a local username's configured initial privilege only
        # when local EXEC authorization is selected. ``none`` is the
        # deliberate fallback for already-authenticated non-local human users;
        # command authorization below still enforces their RADIUS-supplied
        # role. Without this line a privilege-15 local account starts at 1.
        "aaa authorization exec default local none",
        "aaa authorization commands all default local",
        "management ssh",
        "   authentication protocol password",
    ]
    candidate.prepare_lines = prepare
    candidate.activation_lines = activation
    candidate.lines = [*prepare, *activation]
    aaa_rollback = [
        "management ssh",
        "   default authentication protocol",
        "no aaa authorization commands all default local",
        "no aaa authorization exec default",
        "no aaa authentication login default",
        "no aaa authentication login console",
        f"no aaa group server radius {RADIUS_GROUP}",
        f"no radius-server host {server}",
        "no ip radius source-interface",
    ]
    restore_legacy = [_local_account_line(row) for row in legacy_rows]
    remove_prepared = [f"no username {row.username}" for row in reversed(local_rows)]
    candidate.rollback_lines = [*aaa_rollback, *restore_legacy, *remove_prepared]
    candidate.blockers = _radius_policy_blockers(policy.device_name, rows)
    candidate.notes = [
        "Commit and verify prepare_lines first; activation_lines must be one atomic configuration-session commit.",
        "activation_lines retire every LEGACY_SHARED local account so it cannot bypass human RADIUS/TOTP.",
        "rollback_lines disable AAA first, restore legacy recovery access, then remove pilot-only local accounts.",
        "Human usernames must not exist in the EOS local database: unknown local users fall through to RADIUS.",
        "nmas-automation remains a local SERVICE identity and never receives an OTP challenge.",
        "Local EXEC authorization is explicit so local service/break-glass accounts receive their configured privilege 15; "
        "the none fallback preserves the existing post-authentication shell path for non-local RADIUS users.",
        "Microsoft Authenticator supplies a six-digit RFC 6238 TOTP appended directly to the human password.",
        "RADIUS Access-Challenge is not required and remains unverified for EOS SSH.",
        "The cEOS-lab 4.36.2F engineering build ignores tested EOS role restrictions. nmas-automation therefore "
        "retains privilege 15/network-admin because NMAS configuration execution and compensation require it; "
        "credential separation is the smallest enforceable reduction on this image.",
    ]
    return candidate


def render_candidate(policy, credentials) -> MfaCandidate:
    credentials = list(credentials)
    if policy.mechanism == MfaMechanism.RADIUS_TOTP:
        if policy.platform == "arista_ceos":
            candidate = render_ceos_radius_totp_candidate(policy, credentials)
        elif policy.platform == "ubuntu_frr":
            candidate = render_linux_radius_totp_candidate(policy, credentials)
        else:
            return MfaCandidate(device=policy.device_name, platform=policy.platform, supported=False,
                                blockers=["UNSUPPORTED_PLATFORM: no verified RADIUS TOTP mechanism"])
    elif policy.mechanism == MfaMechanism.LEGACY_EOS_SSH_KEY_PASSWORD and policy.platform == "arista_ceos":
        candidate = render_legacy_ceos_candidate(policy.device_name, legacy_accounts_from_credentials(credentials))
    elif policy.mechanism == MfaMechanism.LEGACY_OPENSSH_KEY_PASSWORD and policy.platform == "ubuntu_frr":
        candidate = render_legacy_openssh_candidate(
            policy.device_name,
            legacy_accounts_from_credentials(credentials),
            root_only=all(c.username == "root" for c in credentials),
        )
    else:
        return MfaCandidate(device=policy.device_name, platform=policy.platform, supported=False,
                            blockers=["UNSUPPORTED_PLATFORM: no verified two-factor mechanism"])
    if policy.blocked_reason:
        candidate.blockers.insert(0, policy.blocked_reason)
    return candidate


# ---------------------------------------------------------------------------
# Verification: single factors must be REFUSED, both together ACCEPTED
# ---------------------------------------------------------------------------

ACCEPTED, PARTIAL, REJECTED, ERROR = "ACCEPTED", "PARTIAL", "REJECTED", "ERROR"
PROBES = ("password_only", "key_only", "key_and_wrong_password", "key_and_password")


def evaluate_probe(results: dict[str, str]) -> tuple[bool, str]:
    """Strict verdict: every single-factor or wrong-factor attempt must fail."""
    missing = [name for name in PROBES if name not in results]
    if missing:
        return False, "INCOMPLETE_PROBE"
    if any(results[name] == ERROR for name in PROBES):
        return False, "PROBE_ERROR"
    if results["password_only"] == ACCEPTED:
        return False, "PASSWORD_ALONE_ACCEPTED"
    if results["key_only"] == ACCEPTED:
        return False, "KEY_ALONE_ACCEPTED"
    if results["key_and_wrong_password"] == ACCEPTED:
        return False, "WRONG_SECOND_FACTOR_ACCEPTED"
    if results["key_and_password"] != ACCEPTED:
        return False, "VALID_TWO_FACTOR_LOGIN_REFUSED"
    return True, "TWO_FACTOR_ENFORCED"


def _attempt(transport_factory, username, *, pkey=None, password=None) -> str:
    """One fresh SSH transport per attempt; returns only an outcome label."""
    import paramiko

    try:
        transport = transport_factory()
    except Exception:  # noqa: BLE001 - connection details are never relayed
        return ERROR
    try:
        remaining = None
        if pkey is not None:
            try:
                remaining = transport.auth_publickey(username, pkey)
            except paramiko.AuthenticationException:
                return REJECTED
            if transport.is_authenticated():
                return ACCEPTED
            if password is None:
                return PARTIAL if remaining else REJECTED
        if password is not None:
            try:
                transport.auth_password(username, password)
            except (paramiko.AuthenticationException, paramiko.BadAuthenticationType):
                return REJECTED
        return ACCEPTED if transport.is_authenticated() else PARTIAL
    except Exception:  # noqa: BLE001
        return ERROR
    finally:
        try:
            transport.close()
        except Exception:  # noqa: BLE001
            pass


WRONG_PASSWORD_PROBE = "nmas-2fa-probe-deliberately-wrong"


def probe_two_factor_login(transport_factory, username: str, *, password: str, pkey) -> dict[str, str]:
    """Attempt the four logins; returns outcome labels only (no secret echoes)."""
    return {
        "password_only": _attempt(transport_factory, username, password=password),
        "key_only": _attempt(transport_factory, username, pkey=pkey),
        "key_and_wrong_password": _attempt(transport_factory, username, pkey=pkey, password=WRONG_PASSWORD_PROBE),
        "key_and_password": _attempt(transport_factory, username, pkey=pkey, password=password),
    }
