"""Render a verified report as Markdown (docs/evidence/lab7/RESULTS.md and the Tier-3 job summary) -- numbers are never typed.

``gap_markdown`` renders the baseline gap assessment (docs/evidence/lab7/BASELINE.md) with the same ``figures`` as the
"Baseline" column of RESULTS.md, so the gap assessment and the final result come from one generator.
"""

from __future__ import annotations

from collections import Counter

from .constants import ArtifactStatus, CaseState, CellStatus, Scope


def _pct(x, y) -> str:
    return f"{100.0 * x / y:.2f}%" if y else "n/a"


def _tally(t: dict) -> str:
    return f"{t['pass']} / {t['required']} ({_pct(t['pass'], t['required'])}; missing {t['missing']}, failing {t['fail']}, exempt {t['exempt']})"


def _pair(p) -> str:
    return f"{p[0]} / {p[1]} ({_pct(p[0], p[1])})"


def _row(label, before, after) -> str:
    return f"| {label} | {before} | {after} |"


def figures(report: dict, *, exclude_groups: tuple[str, ...] = ()) -> dict:
    """Headline figures, optionally excluding groups (the baseline excludes the governance package written in this phase)."""
    arts = [a for a in report["artifacts"] if a["scope"] == Scope.CURRENT and a["group"] not in exclude_groups]
    ids = {a["id"] for a in arts}
    unit = [c for c in report["cases"] if c["kind"] != "CELL" and c["artifact"] in ids]
    counted = (CaseState.PASS, CaseState.FAIL, CaseState.MISSING, CaseState.BROKEN_REFERENCE)

    def tally(polarity):
        rows = [c for c in unit if c["polarity"] == polarity]
        states = Counter(c["state"] for c in rows)
        return {"pass": states[CaseState.PASS], "required": sum(states[s] for s in counted), "missing": states[CaseState.MISSING],
                "fail": states[CaseState.FAIL], "exempt": states[CaseState.EXEMPT]}

    statements = sum((a.get("coverage") or {}).get("statements", 0) for a in arts if a["type"] == "PY")
    covered = sum((a.get("coverage") or {}).get("covered", 0) for a in arts if a["type"] == "PY")
    branches = sum((a.get("coverage") or {}).get("branches", 0) for a in arts if a["type"] == "PY")
    covered_b = sum((a.get("coverage") or {}).get("covered_branches", 0) for a in arts if a["type"] == "PY")
    status = Counter(a["status"] for a in arts)
    cells = [c for c in report["cells"] if c["final_status"] == "SUPPORTED"]
    return {
        "positive": tally("POSITIVE"), "negative": tally("NEGATIVE"),
        "functions": (sum(a["functions"]["tested"] for a in arts), sum(a["functions"]["required"] for a in arts)),
        "symbols": sum(len(a["symbols"]) for a in arts),
        "artifacts": (status[ArtifactStatus.CLOSED], sum(1 for a in arts if a["status"] != "COVERAGE_ONLY"), status),
        "lines": (covered, statements), "branches": (covered_b, branches),
        "cells": (sum(c["status"] == CellStatus.CLOSED for c in cells), len(cells)),
        "cell_pos": (sum(c["positive"]["pass"] for c in cells), sum(c["positive"]["required"] for c in cells)),
        "cell_neg": (sum(c["negative"]["pass"] for c in cells), sum(c["negative"]["required"] for c in cells)),
        "pylint": report["summary"]["pylint"], "tests": report["summary"]["tests"],
    }


def results_markdown(final: dict, baseline: dict | None = None, *, title: str = "Lab 7 test governance -- results") -> str:
    f = figures(final)
    b = figures(baseline, exclude_groups=("test_governance",)) if baseline else None

    def both(key, render):
        return render(b[key]) if b else "-", render(f[key])

    lines = [f"# {title}", "",
             "Generated by `manage.py nmas_test_governance summarize` from the hash-verified evidence report(s); do not edit by hand.", "",
             f"* Final evidence: repository SHA `{final.get('repository_sha') or '(working tree)'}`, generated {final['generated_at']}, "
             f"payload sha256 `{final['payload_sha256']}`, mode `{(final.get('provenance') or {}).get('mode', '')}`, "
             f"closure gate **{(final.get('gate') or {}).get('result', '-')}**."]
    if baseline:
        lines.append(f"* Baseline evidence (before Lab 7 tests): SHA `{baseline.get('repository_sha')}`, generated {baseline['generated_at']}, "
                     f"payload sha256 `{baseline['payload_sha256']}`; the governance package written in this phase is excluded from the baseline column.")
    lines += ["", "| Metric | Baseline | Final |", "|---|---|---|"]
    lines.append(_row("Positive cases PASS / required", *both("positive", _tally)))
    lines.append(_row("Negative cases PASS / required", *both("negative", _tally)))
    lines.append(_row("Functions explicitly tested / required", *both("functions", _pair)))
    lines.append(_row("Statements covered", *both("lines", _pair)))
    lines.append(_row("Branches covered", *both("branches", _pair)))
    lines.append(_row("Artifacts closed / counted", *both("artifacts", lambda a: f"{a[0]} / {a[1]}")))
    lines.append(_row("Implemented capability cells closed", *both("cells", _pair)))
    lines.append(_row("Cell positive cases", *both("cell_pos", _pair)))
    lines.append(_row("Cell negative cases", *both("cell_neg", _pair)))
    lines.append(_row("Pylint", *both("pylint", lambda p: f"{p['status']} ({p['critical']} critical, {p['messages']} tracked)")))
    lines.append(_row("Tests in the evidence run", *both("tests", lambda t: ", ".join(f"{k} {v}" for k, v in t.items()))))
    lines.append(_row("Meaningful Python symbols", *both("symbols", str)))
    lines += ["", "## Artifact status (final)", "", "| Status | Artifacts |", "|---|---|"]
    for status_name, count in sorted(f["artifacts"][2].items()):
        lines.append(f"| {status_name} | {count} |")
    lines += ["", "## Generic / control-plane groups (final)", "", "| Group | Artifacts closed | Functions | Positive | Negative | Statements | Branches |",
              "|---|---|---|---|---|---|---|"]
    for g in final["groups"]:
        cov = g["coverage"]
        lines.append(f"| {g['title']} | {g['artifacts_closed']} / {g['artifacts_counted']} | {g['functions']['tested']} / {g['functions']['required']} | "
                     f"{g['positive']['pass']} / {g['positive']['required']} | {g['negative']['pass']} / {g['negative']['required']} | "
                     f"{cov['line_pct']}% | {cov['branch_pct']}% |")
    lines += ["", "## Implemented platform x feature cells (final)", "", "| Platform | Feature | Status | POS | NEG | Known defects |", "|---|---|---|---|---|---|"]
    case_index = {c["id"]: c for c in final["cases"]}
    for c in final["cells"]:
        if c["final_status"] != "SUPPORTED":
            continue
        known = [case_index[i]["stage"] for i in c["case_ids"] if i in case_index and "KNOWN DEFECT" in (case_index[i].get("reason") or "")]
        lines.append(f"| {c['platform']} | {c['feature']} | {c['status']} | {c['positive']['pass']}/{c['positive']['required']} | "
                     f"{c['negative']['pass']}/{c['negative']['required']} | {', '.join(known) or '-'} |")
    lines += ["", "## Lab 7 assignment examples (final)", "", "| Requirement | NMAS function | Negative | Positive |", "|---|---|---|---|"]
    for example in final.get("examples") or []:
        for target in example["targets"]:
            states = target.get("states") or {}
            lines.append(f"| {example['requirement']} | `{target['target']}` | {states.get('NEGATIVE', 'n/a')} | {states.get('POSITIVE', 'n/a')} |")
    gate = final.get("gate") or {}
    lines += ["", "## Closure gate findings (final)", ""]
    for finding in gate.get("findings") or []:
        lines.append(f"* **{finding['severity']}** `{finding['code']}` -- {finding['message']}")
    lines.append("")
    return "\n".join(lines)


def gap_markdown(report: dict, *, exclude_groups: tuple[str, ...] = ("test_governance",)) -> str:
    """Baseline gap assessment: what was missing before the Lab 7 tests, computed from the baseline evidence report."""
    f = figures(report, exclude_groups=exclude_groups)
    lines = ["# Lab 7 baseline gap assessment", "",
             "Generated by `manage.py nmas_test_governance summarize --gap` from the hash-verified baseline evidence report; "
             "do not edit by hand. The baseline is the deployed code before any Lab 7 test was written, measured with the "
             "Lab 7 framework; the governance package written in this phase is excluded" + (f" (groups excluded: {', '.join(exclude_groups)})." if exclude_groups else "."),
             "",
             f"* Evidence: repository SHA `{report.get('repository_sha') or '(working tree)'}`, generated {report['generated_at']}, "
             f"payload sha256 `{report['payload_sha256']}`.", "",
             "| Metric | Baseline |", "|---|---|",
             f"| Positive cases PASS / required | {_tally(f['positive'])} |",
             f"| Negative cases PASS / required | {_tally(f['negative'])} |",
             f"| Functions explicitly tested / required | {_pair(f['functions'])} |",
             f"| Statements covered | {_pair(f['lines'])} |",
             f"| Branches covered | {_pair(f['branches'])} |",
             f"| Artifacts closed / counted | {f['artifacts'][0]} / {f['artifacts'][1]} |",
             f"| Implemented capability cells closed | {_pair(f['cells'])} |",
             f"| Cell positive cases | {_pair(f['cell_pos'])} |",
             f"| Cell negative cases | {_pair(f['cell_neg'])} |",
             f"| Pylint | {f['pylint']['status']} ({f['pylint']['critical']} critical, {f['pylint']['messages']} tracked) |",
             f"| Tests in the evidence run | {', '.join(f'{k} {v}' for k, v in f['tests'].items())} |",
             f"| Meaningful Python symbols | {f['symbols']} |", "",
             "## Gap by group", "",
             "| Group | Artifacts closed | Functions tested | Positive PASS / required | Negative PASS / required | Statements | Branches |",
             "|---|---|---|---|---|---|---|"]
    for g in report["groups"]:
        if g["id"] in exclude_groups:
            continue
        cov = g["coverage"]
        lines.append(f"| {g['title']} | {g['artifacts_closed']} / {g['artifacts_counted']} | {g['functions']['tested']} / {g['functions']['required']} | "
                     f"{g['positive']['pass']} / {g['positive']['required']} | {g['negative']['pass']} / {g['negative']['required']} | "
                     f"{cov['line_pct']}% | {cov['branch_pct']}% |")
    lines += ["", "## Artifact status", "", "| Status | Artifacts |", "|---|---|"]
    for status_name, count in sorted(f["artifacts"][2].items()):
        lines.append(f"| {status_name} | {count} |")
    failing = sorted(t["id"] for t in report["tests"] if t["outcome"] in ("FAIL", "ERROR"))
    lines += ["", "## Tests that did not pass in the baseline run", ""]
    lines += [f"* `{tid}`" for tid in failing] or ["* none"]
    lines.append("")
    return "\n".join(lines)
