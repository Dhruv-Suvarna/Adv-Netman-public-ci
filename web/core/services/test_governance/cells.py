"""Platform x feature cells from the tracked Phase-4 capability ledger (pure JSON; no Django, no database).

The ledger (``docs/evidence/v2-phase4-exhaustive/progress-ledger.json``) is the repository-owned record of the
operator capability matrix: 396 assessed cells, each SUPPORTED or UNSUPPORTED with its probe outcomes.  Only a
SUPPORTED cell is CURRENT test scope.  When a cell moves to SUPPORTED (the ledger is regenerated by
``nmas_capabilities report-matrix``) its required cases become current scope automatically -- nothing else to edit.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from .constants import CAPABILITY_LEDGER, CELL_STAGES

SUPPORTED = "SUPPORTED"

# ledger probe name -> lifecycle stage it evidences (a stage is applicable to a cell when its probe passed)
STAGE_PROBES = {
    "MODEL": ("semantic", "field_validation"),
    "RENDER": ("renderer",),
    "IMPORT": ("parser",),
    "VALIDATE": ("validator",),
    "EXECUTE": ("executor",),
    "COMPENSATION": ("compensation",),
}


class LedgerError(ValueError):
    pass


@dataclass(frozen=True)
class Cell:
    platform: str
    feature: str
    final_status: str
    stages: tuple[str, ...]          # lifecycle stages the capability evidence says are implemented for this cell
    reasons: tuple[str, ...] = ()

    @property
    def key(self) -> str:
        return f"{self.platform}|{self.feature}"

    @property
    def supported(self) -> bool:
        return self.final_status == SUPPORTED


def parse_ledger(data) -> tuple[Cell, ...]:
    if not isinstance(data, dict) or not isinstance(data.get("cells"), list):
        raise LedgerError("capability ledger has no cell list")
    cells, seen = [], set()
    for row in data["cells"]:
        try:
            platform, feature, status = str(row["platform"]), str(row["feature"]), str(row["final_status"])
        except (KeyError, TypeError) as exc:
            raise LedgerError("capability ledger cell is missing platform / feature / final_status") from exc
        if (platform, feature) in seen:
            raise LedgerError(f"duplicate capability cell {platform} {feature}")
        seen.add((platform, feature))
        stages = tuple(stage for stage, _title in CELL_STAGES
                       if all(str(row.get(probe, "")).upper() == "PASS" for probe in STAGE_PROBES[stage]))
        cells.append(Cell(platform, feature, status, stages, tuple(str(r) for r in row.get("unsupported_reasons") or ())))
    return tuple(sorted(cells, key=lambda c: (c.feature, c.platform)))


def load_cells(path: Path | None = None) -> tuple[Cell, ...]:
    target = Path(path or CAPABILITY_LEDGER)
    try:
        return parse_ledger(json.loads(target.read_text(encoding="utf-8")))
    except OSError as exc:
        raise LedgerError(f"cannot read the capability ledger: {type(exc).__name__}") from exc
    except json.JSONDecodeError as exc:
        raise LedgerError("the capability ledger is not valid JSON") from exc


@lru_cache(maxsize=1)
def default_cells() -> tuple[Cell, ...]:
    return load_cells()


def supported_cells(cells: tuple[Cell, ...] | None = None) -> frozenset[tuple[str, str]]:
    return frozenset((c.platform, c.feature) for c in (cells if cells is not None else default_cells()) if c.supported)


def supported_platforms(cells: tuple[Cell, ...] | None = None) -> frozenset[str]:
    return frozenset(p for p, _f in supported_cells(cells))


def cell_case_id(platform: str, feature: str, stage: str, polarity: str) -> str:
    return f"CELL:{platform}:{feature}:{stage}:{polarity}"
