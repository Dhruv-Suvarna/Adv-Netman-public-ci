"""
Phase 4 artwork regression check.

The ten operator-supplied watermark files were added to the working tree
between Phase 3 and Phase 4 (manually, by the operator -- not generated by
any coding agent). This file proves the resolver sees all ten, that they
are served correctly through Django's static-file machinery, that no
unsafe slot name can escape the themes directory, and that theme switching
still renders correctly now that real artwork exists. It does not modify,
regenerate, or move any image.
"""

from django.conf import settings
from django.contrib.staticfiles import finders
from django.test import TestCase
from django.urls import reverse

from core import theme_assets, theme_registry

ALL_SLOTS = list(theme_registry.GLOBAL_ASSET_SLOTS) + [
    context["watermark_slot"]
    for theme in theme_registry.THEMES.values()
    for context in theme["contexts"].values()
]


class AllTenSlotsResolveTests(TestCase):
    def test_exactly_ten_slots_are_declared(self):
        self.assertEqual(len(ALL_SLOTS), 10)

    def test_every_slot_resolves_to_a_static_url(self):
        for slot in ALL_SLOTS:
            with self.subTest(slot=slot):
                url = theme_assets.resolve_watermark_url(slot)
                self.assertIsNotNone(url)
                self.assertTrue(url.startswith(settings.STATIC_URL))

    def test_every_slot_file_exists_on_disk_via_staticfiles_finders(self):
        for slot in ALL_SLOTS:
            with self.subTest(slot=slot):
                found = None
                for ext in ("svg", "png", "webp", "jpg", "jpeg"):
                    found = finders.find(f"core/themes/{slot}/watermark.{ext}")
                    if found:
                        break
                self.assertIsNotNone(found, f"no watermark file found on disk for slot {slot!r}")


class NoPathTraversalTests(TestCase):
    def test_traversal_style_slot_name_does_not_resolve(self):
        for malicious in ("../../../../etc/passwd", "..", "brand/../../secrets"):
            with self.subTest(slot=malicious):
                self.assertIsNone(theme_assets.resolve_watermark_url(malicious))


class ThemeSwitchingStillRendersTests(TestCase):
    def test_every_top_level_theme_renders_home_with_its_own_watermark(self):
        for theme_name in theme_registry.THEMES:
            with self.subTest(theme=theme_name):
                self.client.cookies[settings.THEME_COOKIE_NAME] = theme_name
                response = self.client.get(reverse("core:home"))
                self.assertEqual(response.status_code, 200)
                self.assertContains(response, f'data-theme="{theme_name}"')
                self.assertNotContains(response, "theme-watermark--fallback")

    def test_every_dark_angels_context_resolves_its_own_watermark(self):
        for context_name in theme_registry.THEMES["dark-angels"]["contexts"]:
            slot = theme_registry.THEMES["dark-angels"]["contexts"][context_name]["watermark_slot"]
            with self.subTest(context=context_name):
                self.assertIsNotNone(theme_assets.resolve_watermark_url(slot))

    def test_every_mechanicus_context_resolves_its_own_watermark(self):
        for context_name in theme_registry.THEMES["adeptus-mechanicus"]["contexts"]:
            slot = theme_registry.THEMES["adeptus-mechanicus"]["contexts"][context_name]["watermark_slot"]
            with self.subTest(context=context_name):
                self.assertIsNotNone(theme_assets.resolve_watermark_url(slot))
