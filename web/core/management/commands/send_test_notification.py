"""
Safe synthetic test-notification tool (Phase 4).

Creates ONE notification clearly labelled as a TEST (event_type=TEST,
is_test=True, title/message state it plainly). Exercises real persistence
and, unless --no-slack is given, real (but clearly-labelled) Slack delivery
through the normal publish_event() path -- never a fabricated device
outage, never a NetBox/monitoring/Containerlab touch.

See cleanup_test_notifications for removing rows this command created.
"""

from __future__ import annotations

from django.core.management.base import BaseCommand, CommandError

from core.models import Notification
from core.services import notification_service


class Command(BaseCommand):
    help = (
        "Create a synthetic TEST notification to exercise persistence and, "
        "optionally, Slack delivery. Never touches devices, NetBox, or "
        "monitoring state."
    )

    def add_arguments(self, parser):
        parser.add_argument(
            "--severity",
            default=Notification.Severity.INFO,
            choices=Notification.Severity.values,
            help="Severity to label the test notification with (default: INFO).",
        )
        parser.add_argument("--title", default=None, help="Override the default TEST title.")
        parser.add_argument("--message", default=None, help="Override the default TEST message.")
        parser.add_argument(
            "--no-slack",
            action="store_true",
            help="Skip Slack delivery even if SLACK_WEBHOOK_URL is configured (dry-run for Slack).",
        )
        parser.add_argument(
            "--correlation-key",
            default="",
            help="Optional correlation key, to exercise dedup behavior.",
        )

    def handle(self, *args, **options):
        title = options["title"] or "NMAS Phase 4 Slack integration test"
        message = options["message"] or (
            "This is a synthetic TEST notification generated by "
            "send_test_notification. No real event occurred."
        )
        try:
            notification = notification_service.publish_event(
                event_type=Notification.EventType.TEST,
                severity=options["severity"],
                title=title,
                message=message,
                source="cli.send_test_notification",
                metadata={"generated_by": "send_test_notification"},
                correlation_key=options["correlation_key"],
                notify_slack=not options["no_slack"],
                is_test=True,
            )
        except ValueError as exc:
            raise CommandError(str(exc)) from exc

        self.stdout.write(
            self.style.SUCCESS(
                f"Created TEST notification #{notification.pk} "
                f"(severity={notification.severity}, slack_status={notification.slack_status})"
            )
        )
        if notification.slack_status == Notification.SlackStatus.FAILED:
            self.stdout.write(self.style.WARNING(f"Slack delivery failed: {notification.slack_error}"))
        elif notification.slack_status == Notification.SlackStatus.NOT_CONFIGURED:
            self.stdout.write(
                "Slack is not configured (SLACK_WEBHOOK_URL unset) -- in-app notification only."
            )
